"""Generate unit400_model.py from the extracted JSON data."""
import json
import sys
from pathlib import Path

# Import our translator
sys.path.insert(0, str(Path(__file__).parent))
import unit400_mimic_expr as tx


HERE = Path(__file__).parent
EXTRACTED = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "data" / "extracted"


def load_json(name):
    return json.load(open(EXTRACTED / name))


def build():
    objects = load_json("unit400_objects.json")
    registry = load_json("unit400_registry.json")
    wiring = load_json("unit400_wiring.json")
    init = load_json("unit400_init.json")
    constants = load_json("unit400_constants.json")

    # ---- Build init lookup: (module, tag, attribute) -> (fval, lval) ----
    init_lookup = {}
    for iv in init:
        key = (iv["module"], iv["tag"], iv["attribute"])
        init_lookup[key] = (iv["fval"], iv["lval"])

    # ---- Build per-object init dicts ----
    per_obj_init = {}
    for iv in init:
        key = (iv["module"], iv["tag"])
        per_obj_init.setdefault(key, {})[iv["attribute"]] = iv["fval"]

    # ---- Object type → Python class name ----
    type_to_class = {
        "IN_PARAM": "InParamObject",
        "OUT_PARAM": "OutParamObject",
        "CALC": None,  # special — generated subclass
        "MULT": "MultObject",
        "ADD": "AddObject",
        "DIV": "DivObject",
        "NOT": "NotObject",
        "CMP": "CmpObject",
        "FOF": "FofObject",
        "HX": "HXObject",
        "ANALOGVALVE": "AnalogValveObject",
        "RNG": "RngObject",
        "LABEL": None,  # skip — cosmetic
    }

    # ---- Emit file ----
    lines = []
    lines.append('"""')
    lines.append("Unit 400 Hybrid simulation — AUTO-GENERATED by generate_model.py.")
    lines.append("")
    lines.append("Do not edit this file by hand. Edit generate_model.py instead.")
    lines.append('"""')
    lines.append("import json")
    lines.append("import math")
    lines.append("import random")
    lines.append("from pathlib import Path")
    lines.append("")
    lines.append("from unit400_equations import (")
    lines.append("    BaseObject, InParamObject, OutParamObject,")
    lines.append("    MultObject, AddObject, DivObject, NotObject, CmpObject,")
    lines.append("    FofObject, HXObject, AnalogValveObject, RngObject,")
    lines.append("    CalcObject,")
    lines.append(")")
    lines.append("")

    # ---- Emit CALC subclasses ----
    lines.append("# ============================================================")
    lines.append("# CALC subclass definitions (24 generated from expressions)")
    lines.append("# ============================================================")
    calc_count = 0
    for o in objects:
        if o["type"] != "CALC":
            continue
        module = o["fields"].get("MODULE_NAME", "")
        tag = o["fields"].get("TAG", "")
        expr = o["fields"].get("EXPRESSION", "")
        cls_src = tx.generate_calc_class(module, tag, expr)
        lines.append(cls_src)
        calc_count += 1
    lines.append("")
    lines.append("")

    # ---- Emit object data table (as Python literals for readability) ----
    lines.append("# ============================================================")
    lines.append("# Object data — 210 entries from the MIMIC export")
    lines.append("# ============================================================")
    lines.append("OBJECTS = [")
    for o in objects:
        if o["type"] == "LABEL":
            continue  # skip cosmetic
        module = o["fields"].get("MODULE_NAME", "")
        tag = o["fields"].get("TAG", "")
        obj_type = o["type"]
        # Get init dict for this object
        oi = per_obj_init.get((module, tag), {})
        # Emit as (type, module, tag, fields, init)
        lines.append("    {")
        lines.append("        'type': %r," % obj_type)
        lines.append("        'module': %r," % module)
        lines.append("        'tag': %r," % tag)
        lines.append("        'fields': %r," % dict(o["fields"]))
        lines.append("        'init': %r," % dict(oi))
        lines.append("    },")
    lines.append("]")
    lines.append("")

    # ---- Emit wiring table ----
    lines.append("# ============================================================")
    lines.append("# Signal wiring — 146 connections from <WIRES>")
    lines.append("# ============================================================")
    lines.append("WIRES = [")
    for w in wiring:
        lines.append("    {")
        lines.append("        'module': %r," % w.get("module"))
        lines.append("        'source_tag': %r," % w.get("source_tag"))
        lines.append("        'source_param': %r," % w.get("source_param"))
        lines.append("        'dest_tag': %r," % w.get("dest_tag"))
        lines.append("        'dest_param': %r," % w.get("dest_param"))
        lines.append("        'gain': %r," % w.get("gain"))
        lines.append("        'offset': %r," % w.get("offset"))
        lines.append("    },")
    lines.append("]")
    lines.append("")

    # ---- Emit registry ----
    lines.append("# ============================================================")
    lines.append("# Object registry — 181 tag→type mappings")
    lines.append("# ============================================================")
    lines.append("REGISTRY = [")
    for r in registry:
        lines.append("    {'module': %r, 'type': %r, 'tag': %r, 'block_number': %r},"
                     % (r.get("module"), r.get("type"), r.get("tag"), r.get("block_number")))
    lines.append("]")
    lines.append("")

    # ---- Emit constants ----
    lines.append("# ============================================================")
    lines.append("# User constants")
    lines.append("# ============================================================")
    const_dict = {c["name"]: float(c["value"]) for c in constants}
    lines.append("CONSTANTS = %r" % const_dict)
    lines.append("")

    # ---- Emit the model class ----
    lines.append("")
    lines.append("class Unit400Model:")
    lines.append('    """Complete Unit 400 Hybrid simulation in pure Python."""')
    lines.append("")
    lines.append("    def __init__(self):")
    lines.append("        self.constants = dict(CONSTANTS)")
    lines.append("        self.objects = {}    # (module, tag) -> object instance")
    lines.append("        self._registry = {}  # tag -> (module, object)")
    lines.append("        self.external = {}    # external C300 tag path -> value")
    lines.append("        self._build_objects()")
    lines.append("        self._build_wires()")
    lines.append("")
    lines.append("    def set_external(self, path, value):")
    lines.append("        self.external[path] = float(value)")
    lines.append("        # Also refresh any IN_PARAM that reads this address")
    lines.append("        for obj in self.objects.values():")
    lines.append("            if getattr(obj, 'field_address', None) == path:")
    lines.append("                obj.outputs['OUT'] = float(value)")
    lines.append("")
    lines.append("")
    lines.append("    def _build_objects(self):")
    lines.append("        cls_map = {")
    lines.append("            'IN_PARAM': InParamObject,")
    lines.append("            'OUT_PARAM': OutParamObject,")
    lines.append("            'MULT': MultObject,")
    lines.append("            'ADD': AddObject,")
    lines.append("            'DIV': DivObject,")
    lines.append("            'NOT': NotObject,")
    lines.append("            'CMP': CmpObject,")
    lines.append("            'FOF': FofObject,")
    lines.append("            'HX': HXObject,")
    lines.append("            'ANALOGVALVE': AnalogValveObject,")
    lines.append("            'RNG': RngObject,")
    lines.append("        }")
    lines.append("        for entry in OBJECTS:")
    lines.append("            obj_type = entry['type']")
    lines.append("            module = entry['module']")
    lines.append("            tag = entry['tag']")
    lines.append("            if obj_type == 'CALC':")
    lines.append("                cls_name = 'Calc_%s_%s' % (module, tag)")
    lines.append("                cls_name = cls_name.replace('-', '_').replace('.', '_')")
    lines.append("                cls = globals().get(cls_name)")
    lines.append("                if cls is None:")
    lines.append("                    raise RuntimeError('Missing CALC class: ' + cls_name)")
    lines.append("                obj = cls(module, tag, entry['fields'], entry['init'])")
    lines.append("            else:")
    lines.append("                cls = cls_map.get(obj_type)")
    lines.append("                if cls is None:")
    lines.append("                    continue  # skip unknown types")
    lines.append("                obj = cls(module, tag, entry['fields'], entry['init'])")
    lines.append("            obj.model = self")
    lines.append("            self.objects[(module, tag)] = obj")
    lines.append("            # Index by bare tag for convenience")
    lines.append("            self._registry[(module, tag)] = obj")
    lines.append("")
    lines.append("    def _build_wires(self):")
    lines.append("        self._wires = []")
    lines.append("        for w in WIRES:")
    lines.append("            src_key = (w['module'], w['source_tag'])")
    lines.append("            dst_key = (w['module'], w['dest_tag'])")
    lines.append("            src = self.objects.get(src_key)")
    lines.append("            dst = self.objects.get(dst_key)")
    lines.append("            if src is None or dst is None:")
    lines.append("                continue")
    lines.append("            self._wires.append((src, w['source_param'], dst, w['dest_param'],")
    lines.append("                                float(w['gain']), float(w['offset'])))")
    lines.append("")
    lines.append("    def read(self, path):")
    lines.append('        """Read a value by path. Handles external, 3-part, 2-part, and 1-part.')
    lines.append('        Searches all modules for 2-part and 1-part paths.\"\"\"')
    lines.append("        if path in self.external:")
    lines.append("            return self.external[path]")
    lines.append("        parts = path.split(chr(47))")  # "/"
    lines.append("        if len(parts) == 3:")
    lines.append("            module, tag, port = parts")
    lines.append("            obj = self.objects.get((module, tag))")
    lines.append("            if obj is not None:")
    lines.append("                return obj.get_output(port)")
    lines.append("            return 0.0")
    lines.append("        if len(parts) == 2:")
    lines.append("            tag, port = parts")
    lines.append("            # Search all modules for this tag")
    lines.append("            for (m, t), o in self.objects.items():")
    lines.append("                if t == tag:")
    lines.append("                    return o.get_output(port)")
    lines.append("            return 0.0")
    lines.append("        if len(parts) == 1:")
    lines.append("            tag = parts[0]")
    lines.append("            for (m, t), o in self.objects.items():")
    lines.append("                if t == tag:")
    lines.append("                    return o.get_output('OUT')")
    lines.append("            return 0.0")
    lines.append("        return 0.0")
    lines.append("    def _propagate_wires(self):")
    lines.append("        for src, sport, dst, dport, gain, offset in self._wires:")
    lines.append("            v = src.get_output(sport)")
    lines.append("            dst.set_input(dport, v * gain + offset)")
    lines.append("")
    lines.append("    def _evaluate_all(self):")
    lines.append("        # IN_PARAMs first (pull externals)")
    lines.append("        for obj in self.objects.values():")
    lines.append("            if obj.TYPE == 'IN_PARAM':")
    lines.append("                try:")
    lines.append("                    obj.evaluate()")
    lines.append("                except Exception:")
    lines.append("                    pass")
    lines.append("        # Then everything else")
    lines.append("        for obj in self.objects.values():")
    lines.append("            if obj.TYPE != 'IN_PARAM':")
    lines.append("                try:")
    lines.append("                    obj.evaluate()")
    lines.append("                except Exception:")
    lines.append("                    pass")
    lines.append("")
    lines.append("    def step(self, dt):")
    lines.append('        """Advance the model by dt seconds."""')
    lines.append("        self._propagate_wires()")
    lines.append("        # Multi-pass convergence (chain depth ~5-6)")
    lines.append("        for _ in range(15):")
    lines.append("            self._evaluate_all()")
    lines.append("            self._propagate_wires()")
    lines.append("        # Dynamic update")
    lines.append("        for obj in self.objects.values():")
    lines.append("            if hasattr(obj, 'step'):")
    lines.append("                try:")
    lines.append("                    obj.step(dt)")
    lines.append("                except Exception:")
    lines.append("                    pass")
    lines.append("        self._propagate_wires()")
    lines.append("")
    lines.append("    def snapshot(self):")
    lines.append('        """Return a flat dict of all outputs for inspection."""')
    lines.append("        snap = {}")
    lines.append("        for (module, tag), obj in self.objects.items():")
    lines.append("            for port, val in obj.outputs.items():")
    lines.append("                snap['%s/%s/%s' % (module, tag, port)] = val")
    lines.append("        return snap")
    lines.append("")

    out_path = HERE / "unit400_model.py"
    out_path.write_text("\n".join(lines))
    print("Wrote", out_path)
    print("  CALC classes:", calc_count)
    print("  Objects:", len([o for o in objects if o["type"] != "LABEL"]))
    print("  Wires:", len(wiring))
    print("  Registry:", len(registry))


if __name__ == "__main__":
    build()
